class _HybridRow(dict):
    """Dict-style PostgreSQL row that also supports the numeric indexing used by SQLite rows."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class _PgCursor:
    def __init__(self, cursor):
        self._cursor = cursor

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def _row(self, row):
        return _HybridRow(row) if row is not None else None

    def fetchone(self):
        return self._row(self._cursor.fetchone())

    def fetchall(self):
        return [self._row(row) for row in self._cursor.fetchall()]

    def __iter__(self):
        return (self._row(row) for row in self._cursor)


class _PgConnection:
    def __init__(self, connection):
        self._connection = connection

    @staticmethod
    def _sql(sql):
        sql = re.sub(r'\bINSERT\s+OR\s+IGNORE\s+INTO\b', 'INSERT INTO', sql, flags=re.I)
        # qmark placeholders are used throughout the local SQLite implementation.
        sql = sql.replace('?', '%s')
        if re.match(r'^\s*INSERT\s+INTO\s+roles\b', sql, flags=re.I) and '(SELECT COALESCE(MAX(sort)' in sql:
            sql = sql.replace('(SELECT COALESCE(MAX(sort), 0) + 1 FROM roles)', '(SELECT COALESCE(MAX(sort), 0) + 1 FROM roles)')
        if re.match(r'^\s*INSERT\s+INTO\s+(roles|settings)\b', sql, flags=re.I) and 'ON CONFLICT' not in sql.upper():
            sql = sql.rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'
        return sql

    def execute(self, sql, params=()):
        if re.match(r'^\s*PRAGMA\b', sql, flags=re.I):
            return _PgCursor(self._connection.execute('SELECT 1'))
        return _PgCursor(self._connection.execute(self._sql(sql), params or ()))

    def executescript(self, script):
        schema = script.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        schema += '\nCREATE UNIQUE INDEX IF NOT EXISTS ix_users_username_lower ON users (LOWER(username));'
        for statement in schema.split(';'):
            if statement.strip():
                self.execute(statement)

    def close(self):
        self._connection.close()



def utcnow() -> str:
    return datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


def connect(path: str | None = None, database_url: str | None = None):
    url = database_url or os.environ.get('DATABASE_URL')
    if url:
        if psycopg is None:
            raise RuntimeError('Install psycopg[binary] to use the PostgreSQL database.')
        raw = psycopg.connect(url, autocommit=True, row_factory=dict_row, connect_timeout=10)
        return _PgConnection(raw)
    if os.environ.get('VERCEL') == '1':
        raise RuntimeError('Set DATABASE_URL to a persistent PostgreSQL connection string in Vercel project settings.')
    con = sqlite3.connect(path or ':memory:', timeout=20, isolation_level=None)
    con.row_factory = sqlite3.Row
    con.execute('PRAGMA journal_mode=WAL')
    con.execute('PRAGMA busy_timeout=20000')
    return con


def get_db():
    if '_db' not in g:
        g._db = connect(current_app.config.get('DB_PATH'), current_app.config.get('DATABASE_URL'))
    return g._db


def close_db(_exc=None) -> None:
    con = g.pop('_db', None)
    if con is not None:
        con.close()


def init_schema(con) -> None:
    con.executescript(SCHEMA)
    if not con.execute('SELECT 1 FROM roles LIMIT 1').fetchone():
        for i, (name, perms) in enumerate(E.DEFAULT_ROLES.items()):
            con.execute('INSERT INTO roles(name, perms, sort) VALUES(?,?,?)', (name, json.dumps(perms), i))
    con.execute("INSERT OR IGNORE INTO settings(key, value) VALUES('main', ?)", (json.dumps(DEFAULT_SETTINGS),))


def init_app(app) -> None:
    app.teardown_appcontext(close_db)
    with app.app_context():
        init_schema(get_db())


@contextmanager
def tx():
    """Serialize audit-producing writes, including across concurrent PostgreSQL functions."""
    con = get_db()
    with _LOCK:
        con.execute('BEGIN IMMEDIATE' if isinstance(con, sqlite3.Connection) else 'BEGIN')
        try:
            if not isinstance(con, sqlite3.Connection):
                con.execute('SELECT pg_advisory_xact_lock(724139205)')
            yield con
        except BaseException:
            con.execute('ROLLBACK')
            raise
        else:
            con.execute('COMMIT')


def _hash(prev, ts, uid, uname, action, entity, detail) -> str:
    blob = json.dumps([prev, ts, uid, uname, action, entity, detail], ensure_ascii=True, separators=(',', ':'))
    return hashlib.sha256(blob.encode('ascii')).hexdigest()


def audit(con, action: str, entity: str = '', detail: str = '', user=None, username: str = '') -> None:
    with _LOCK:
        row = con.execute('SELECT hash FROM audit ORDER BY id DESC LIMIT 1').fetchone()
        prev = row['hash'] if row else GENESIS
        ts, uid = utcnow(), (user['id'] if user else None)
        uname = user['username'] if user else username
        entity, detail = str(entity)[:200], str(detail)[:600]
        con.execute('INSERT INTO audit(ts,user_id,username,action,entity,detail,prev_hash,hash) VALUES(?,?,?,?,?,?,?,?)',
                    (ts, uid, uname, action, entity, detail, prev, _hash(prev, ts, uid, uname, action, entity, detail)))


def verify_audit(con) -> dict:
    prev, n = GENESIS, 0
    for r in con.execute('SELECT * FROM audit ORDER BY id'):
        n += 1
        if r['prev_hash'] != prev or r['hash'] != _hash(prev, r['ts'], r['user_id'], r['username'], r['action'], r['entity'], r['detail']):
            return {'ok': False, 'count': n, 'bad_id': r['id']}
        prev = r['hash']
    return {'ok': True, 'count': n, 'head': prev}


def get_settings(con) -> dict:
    st = dict(DEFAULT_SETTINGS)
    row = con.execute("SELECT value FROM settings WHERE key='main'").fetchone()
    if row:
        try:
            st.update(json.loads(row['value']))
        except ValueError:
            pass
    return st


def save_settings(con, st: dict) -> None:
    con.execute("INSERT INTO settings(key, value) VALUES('main', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (json.dumps(st),))


def get_meta(con) -> dict:
    return {r['key']: r['value'] for r in con.execute('SELECT key, value FROM meta')}


def set_meta(con, **kw) -> None:
    for k, v in kw.items():
        con.execute('INSERT INTO meta(key, value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value', (k, None if v is None else str(v)))


def today_serial() -> int:
    return (datetime.now(DHAKA).date() - E.EPOCH).days


def as_of_serial(st: dict) -> int:
    if st.get('as_of_mode') == 'fixed' and st.get('as_of_fixed') is not None:
        return int(st['as_of_fixed'])
    return today_serial()
